#!/usr/bin/env python3
"""
Database migration CLI using Alembic.
Integrated with your DatabaseManager.

Usage:
    python migrate_alembic.py [command] [args]

Commands:
    init          Initialize Alembic (run once)
    create        Create new migration
    upgrade       Upgrade to latest version
    downgrade     Downgrade one version
    history       Show migration history
    current       Show current version
    stamp         Stamp database without running migrations
    status        Show migration status
"""
import os
import sys
import argparse
from pathlib import Path

# Add project root to path
print(f"adding : {Path(__file__).parent.parent}")
sys.path.insert(0, str(Path(__file__).parent.parent))


def run_alembic_command(args):
    """Run alembic command directly."""
    from alembic.config import main

    sys.argv = ["alembic"] + args
    main()


def run_with_db_manager(args):
    """Run migration commands using DatabaseManager."""
    from core.database import db_manager, init_database
    from core.config import _load_config as get_config

    # Initialize database
    try:
        config = get_config()
        db_path = config.get("database.path", "data")
        db_path = os.path.join(db_path, "app.db")
    except:
        db_path = "data/app.db"

    print(f"Initializing database at {db_path}...")
    init_database(use_memory=False, db_path=db_path, auto_upgrade=False)

    command = args[0] if args else ""

    if command == "upgrade":
        revision = args[1] if len(args) > 1 else "head"
        print(f"Upgrading to {revision}...")
        success = db_manager.check_and_upgrade_schema(revision)
        if success:
            print("✅ Upgrade completed successfully")
        else:
            print("❌ Upgrade failed")
            sys.exit(1)

    elif command == "create":
        if len(args) < 2:
            print("Error: Migration message required")
            sys.exit(1)
        message = args[1]
        autogenerate = "--empty" not in args
        print(f"Creating {'autogenerated' if autogenerate else 'empty'} migration: {message}")
        success = db_manager.create_migration(message, autogenerate)
        if success:
            print("✅ Migration created successfully")
        else:
            print("❌ Failed to create migration")
            sys.exit(1)

    elif command == "status":
        status = db_manager.get_migration_status()
        print("\n=== Database Migration Status ===")
        print(f"Alembic available: {status['alembic_available']}")
        print(f"Database initialized: {status['database_initialized']}")
        print(f"In-memory: {status['in_memory']}")
        if status['current_revision']:
            print(f"Current revision: {status['current_revision'][:8]}")
        if status['head_revision']:
            print(f"Head revision: {status['head_revision'][:8]}")
        print(f"Needs upgrade: {status['needs_upgrade']}")

    elif command == "stamp":
        revision = args[1] if len(args) > 1 else "head"
        print(f"Stamping database with revision {revision}...")
        success = db_manager.stamp_database(revision)
        if success:
            print("✅ Database stamped successfully")
        else:
            print("❌ Failed to stamp database")
            sys.exit(1)

    else:
        return False

    return True


def main():
    parser = argparse.ArgumentParser(description="Database migration helper")
    subparsers = parser.add_subparsers(dest="command", help="Command to run")

    # Init command
    subparsers.add_parser("init", help="Initialize Alembic (first time only)")

    # Create migration
    create_parser = subparsers.add_parser("create", help="Create new migration")
    create_parser.add_argument("message", help="Migration message")
    create_parser.add_argument("--empty", action="store_true",
                              help="Create empty migration (no autogenerate)")

    # Upgrade
    upgrade_parser = subparsers.add_parser("upgrade", help="Upgrade database")
    upgrade_parser.add_argument("revision", nargs="?", default="head",
                               help="Revision to upgrade to (default: head)")

    # Downgrade
    downgrade_parser = subparsers.add_parser("downgrade", help="Downgrade database")
    downgrade_parser.add_argument("revision", nargs="?", default="-1",
                                 help="Revision to downgrade to (default: -1)")

    # Other commands
    subparsers.add_parser("history", help="Show migration history")
    subparsers.add_parser("current", help="Show current revision")
    subparsers.add_parser("status", help="Show migration status")

    stamp_parser = subparsers.add_parser("stamp", help="Stamp database")
    stamp_parser.add_argument("revision", nargs="?", default="head",
                             help="Revision to stamp (default: head)")

    args = parser.parse_args()

    if not args.command:
        parser.print_help()
        return 1

    # Handle init command separately
    if args.command == "init":
        from init_alembic import init_alembic
        success = init_alembic()
        return 0 if success else 1

    # Commands that work better with Alembic directly
    direct_alembic_commands = ["history", "current", "downgrade"]

    if args.command in direct_alembic_commands:
        if args.command == "downgrade":
            run_alembic_command([args.command, args.revision])
        else:
            run_alembic_command([args.command])
        return 0

    # Commands that use DatabaseManager
    if args.command == "create":
        cmd_args = [args.command, args.message]
        if args.empty:
            cmd_args.append("--empty")
        success = run_with_db_manager(cmd_args)
    elif args.command == "upgrade":
        success = run_with_db_manager([args.command, args.revision])
    elif args.command == "stamp":
        success = run_with_db_manager([args.command, args.revision])
    elif args.command == "status":
        success = run_with_db_manager([args.command])
    else:
        print(f"Unknown command: {args.command}")
        return 1

    return 0 if success else 1


if __name__ == "__main__":
    sys.exit(main())
